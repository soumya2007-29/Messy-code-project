SCORE_COUNT = 3

students = [
    ["Rahul", 78, 88, 92],
    ["Priya", 65, 71, 69],
    ["Amit", 90, 94, 85],
    ["Sneha", 55, 60, 58],
    ["Vikram", 82, 79, 88]
]


def sum_scores(student):
    """Return the total of a student's numeric scores, skipping the name."""
    total = 0
    for index in range(1, len(student)):
        total = total + student[index]
    return total


def average_score(student):
    """Return a student's average across SCORE_COUNT numeric scores."""
    return sum_scores(student) / SCORE_COUNT


def class_average(students):
    """Return the mean of all students' averages."""
    total = 0
    for student in students:
        total = total + average_score(student)
    return total / len(students)


def count_above_class_average(students):
    """Return how many students scored above the class average."""
    mean = class_average(students)
    count = 0
    for student in students:
        if average_score(student) > mean:
            count = count + 1
    return count


print("REPORT")

for student in students:
    total = sum_scores(student)
    average = average_score(student)

    if average >= 90:
        grade = "A"
    elif average >= 80:
        grade = "B"
    elif average >= 70:
        grade = "C"
    elif average >= 60:
        grade = "D"
    else:
        grade = "F"

    print(f"{student[0]}{total}{average}{grade}")

print(f"Class average:{class_average(students)}")
print(f"Above class average:{count_above_class_average(students)}")

highest_average = 0
topper_name = ""

for student in students:
    average = average_score(student)

    if average > highest_average:
        highest_average = average
        topper_name = student[0]

print(f"Topper:{topper_name}{highest_average}")
